export const useThemeStore = create(
  persist(
    (set) => ({
      themeMode: "dark",
      themePreset: "default",
      backgroundType: "animated", // 'none' | 'image' | 'animated' | 'video'
      motionPreset: "punk-records-core",
      iconShape: "circle", // 'circle' | 'star' | 'code' | 'spark'
      backgroundImage: "",
      backgroundVideo: "",

      setThemeMode: (mode) => set({ themeMode: mode }),
      setThemePreset: (preset) => set({ themePreset: preset }),
      setBackgroundType: (type) => set({ backgroundType: type }),
      setMotionPreset: (motion) => set({ motionPreset: motion }),
      setIconShape: (shape) => set({ iconShape: shape }),
      setBackgroundImage: (url) => set({ backgroundImage: url }),
      setBackgroundVideo: (url) => set({ backgroundVideo: url }),

      resetTheme: () =>
        set({
          themeMode: "dark",
          themePreset: "default",
          backgroundType: "animated",
          motionPreset: "punk-records-core",
          iconShape: "circle",
          backgroundImage: "",
          backgroundVideo: "",
        }),
    }),
    {
      name: "vegarecords-theme",
      storage: createJSONStorage(() => localStorage),
    }
  )
);

